import type { ReactNode } from 'react'
import { DemoRefTag, SeverityBadge } from '@/components/analysis/analysis-badges'
import { Button } from '@/components/ui/button'
import { Dialog, DialogClose, DialogContent, DialogDescription, DialogHeader, DialogTitle } from '@/components/ui/dialog'
import { Notice } from '@/components/ui/notice'
import { conflictMessage } from '@/lib/correction'
import type { Applicability, CorrectionSuggestion, SuggestionStatus } from '@/types/correction'
import { CategoryBadge, SuggestionStatusBadge } from './correction-badges'

function Section({ title, children }: { title: string; children: ReactNode }) {
  return (
    <section className="space-y-1">
      <h3 className="text-xs font-medium uppercase tracking-wide text-muted-foreground">{title}</h3>
      <div className="break-words text-sm leading-relaxed">{children}</div>
    </section>
  )
}

interface SuggestionDetailDialogProps {
  suggestion: CorrectionSuggestion | null
  status: SuggestionStatus
  applicability: Applicability
  isDemo: boolean
  onClose: () => void
}

export function SuggestionDetailDialog({ suggestion, status, applicability, isDemo, onClose }: SuggestionDetailDialogProps) {
  const conflict = suggestion && status === 'pending' ? conflictMessage(applicability) : null
  return (
    <Dialog open={suggestion !== null} onOpenChange={(next) => !next && onClose()}>
      <DialogContent className="max-h-[90vh] max-w-2xl overflow-y-auto">
        {suggestion && (
          <>
            <DialogHeader>
              <DialogTitle>Suggestion details</DialogTitle>
              <DialogDescription>
                {isDemo ? 'A demonstration suggestion written by hand. It was not generated by AI.' : 'Suggested correction for this submission.'}
              </DialogDescription>
            </DialogHeader>

            <div className="flex flex-wrap items-center gap-2">
              <CategoryBadge category={suggestion.category} />
              <SeverityBadge severity={suggestion.severity} />
              <SuggestionStatusBadge status={status} />
            </div>

            <Section title="Original text">
              <p className="whitespace-pre-wrap rounded-md bg-primary-soft px-3 py-2 text-primary-soft-foreground line-through decoration-primary/60">
                {suggestion.originalText.trim()}
              </p>
            </Section>

            <Section title="Suggested replacement">
              {suggestion.suggestedText === '' ? (
                <p className="rounded-md bg-muted px-3 py-2 italic text-muted-foreground">Remove this text.</p>
              ) : (
                <p className="whitespace-pre-wrap rounded-md bg-success-soft px-3 py-2 font-medium text-success underline decoration-success/50 underline-offset-2">
                  {suggestion.suggestedText}
                </p>
              )}
            </Section>

            <Section title="Explanation">{suggestion.explanation}</Section>
            <Section title="Why this improves compliance">{suggestion.whyItImproves}</Section>

            <Section title="Related guideline or approved knowledge">
              {suggestion.guideline ? (
                <div className="space-y-1 rounded-md border border-border p-3">
                  <p className="font-medium">{suggestion.guideline.title}</p>
                  <p className="text-xs text-muted-foreground">{suggestion.guideline.category}</p>
                  <p>{suggestion.guideline.excerpt}</p>
                </div>
              ) : (
                <span className="text-muted-foreground">No approved guideline or knowledge matched this text.</span>
              )}
            </Section>

            <Section title="Evidence reference">
              {suggestion.evidenceRef ? (
                <>
                  {suggestion.evidenceRef}
                  <DemoRefTag show={isDemo} />
                </>
              ) : (
                <span className="text-muted-foreground">No approved evidence found.</span>
              )}
            </Section>

            {conflict && <Notice tone="error">{conflict}</Notice>}

            <Notice tone="info">
              This is a suggestion only. You decide whether to accept it, and a human reviewer makes the final decision on the content.
            </Notice>

            <div className="flex justify-end border-t border-border pt-4">
              <DialogClose asChild>
                <Button variant="ghost">Close</Button>
              </DialogClose>
            </div>
          </>
        )}
      </DialogContent>
    </Dialog>
  )
}
